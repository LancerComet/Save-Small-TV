/**
 * Uncle Enemy - 穿西装提公文包的公务员大叔
 * 带有四种能力的强力敌人
 */
class UncleEnemy extends Enemy {
  width = WIDTH
  height = HEIGHT
  textures = bitmapsToTextures(WIDTH, HEIGHT, BITMAPS, COLOR_MAP)

  constructor () {
    super()
    this.x = 0
    this.y = 0
    this.hp = UNCLE_MAX_HP
    this.maxHp = UNCLE_MAX_HP // 设置最大血量，用于血条显示
    this.speed = 48 // Uncle 移动较慢（公务员嘛）
    this.paddingX = 4
    this.paddingY = 4
    this.TEXTURE_CHANGING_COUNTDOWN = 15
    this.destroyCountdown = 0
    this.attack = 50 // Uncle 接触伤害很高（公务员压迫感）

    // 精英敌人属性
    this.isElite = true // 不会因出界被删除
    this.scoreValue = 100 // 击杀得分
    this.dropCount = 2 // 掉落2个道具

    // 设置行为 - 缓慢追踪玩家
    this.setBehavior(new ChaseBehavior({ speed: 30 }))

    // 添加四种能力
    // 1. 普通射击 - 快速单发（公文攻击）
    this.addAbility(new ShootAbility({
      cooldown: 1.5,
      bulletSpeed: 100,
      bulletDamage: 15,
      bulletSize: 5,
      bulletColor: '#1a1a2e' // 深色西装色
    }))

    // 2. 爆发射击 - 圆形弹幕（官僚主义）
    this.addAbility(new BurstAbility({
      cooldown: 4,
      bulletCount: 12,
      bulletSpeed: 120,
      bulletDamage: 10,
      spreadAngle: 0, // 360 度
      aimAtTarget: false,
      bulletColor: '#cc0000' // 红色领带色
    }))

    // 3. 追踪弹（持续跟踪的压力）
    this.addAbility(new HomingAbility({
      cooldown: 5,
      bulletSpeed: 60,
      bulletDamage: 20,
      turnSpeed: 3,
      lifetime: 8
    }))

    // 4. 死亡爆炸（最后的怒气）
    this.addAbility(new ExplodeAbility({
      fragmentCount: 16,
      fragmentSpeed: 240,
      fragmentDamage: 25
    }))
  }
}

